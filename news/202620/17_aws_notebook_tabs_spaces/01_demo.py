# MAGIC ## Explain
# MAGIC
# MAGIC An editor space remembers tabs and anchors navigation/search to a folder. Switching spaces restores the selected project's tabs.
# MAGIC
# MAGIC Editor spaces are personal organization. They are different from Genie conversational spaces and from the App Spaces that govern apps.

